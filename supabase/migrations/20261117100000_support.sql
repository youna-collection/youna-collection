-- SAV : numéro lisible, suivi des échanges, articles concernés et photos.
-- Les clientes (avec ou sans compte) passent par le serveur, qui vérifie leurs droits
-- et le délai de retour : elles ne peuvent plus écrire directement dans ces tables.

alter table public.support_tickets
  add column number bigint generated by default as identity (start with 101) unique,
  add column last_message_at timestamptz not null default now(),
  add column last_author public.message_author not null default 'customer';

create index support_tickets_last_message_at_idx on public.support_tickets (last_message_at desc);

-- Articles concernés par un retour ou un échange.
create table public.support_ticket_items (
  ticket_id uuid not null references public.support_tickets (id) on delete cascade,
  order_item_id uuid not null references public.order_items (id) on delete cascade,
  quantity integer not null check (quantity > 0 and quantity <= 1000),
  primary key (ticket_id, order_item_id)
);
create index support_ticket_items_order_item_id_idx on public.support_ticket_items (order_item_id);

-- Photos jointes à un message (3 au plus, vérifié par le serveur). Fichiers privés.
create table public.support_attachments (
  id uuid primary key default gen_random_uuid(),
  message_id uuid not null references public.support_messages (id) on delete cascade,
  path text not null unique check (char_length(path) <= 300),
  content_type text not null check (content_type in ('image/jpeg', 'image/png', 'image/webp')),
  size_bytes integer not null check (size_bytes > 0 and size_bytes <= 5242880),
  created_at timestamptz not null default now()
);
create index support_attachments_message_id_idx on public.support_attachments (message_id);

alter table public.support_ticket_items enable row level security;
alter table public.support_attachments enable row level security;

-- Chaque message met à jour la demande : date du dernier échange, et qui doit répondre.
-- Une cliente qui répond rouvre une demande « en attente » ou « résolue ».
create function public.support_message_touch_ticket()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.support_tickets
    set last_message_at = new.created_at,
        last_author = new.author_role,
        status = case
          when new.author_role = 'customer' and status in ('waiting_customer', 'resolved') then 'open'::public.ticket_status
          else status
        end
    where id = new.ticket_id;
  return new;
end;
$$;
revoke all on function public.support_message_touch_ticket() from public, anon, authenticated;

create trigger support_message_touch_ticket
  after insert on public.support_messages
  for each row execute function public.support_message_touch_ticket();

-- Droits : lecture et réponses pour l'admin ; tout le reste passe par le serveur.
drop policy support_tickets_insert_own on public.support_tickets;
revoke insert on public.support_tickets from authenticated;

drop policy support_messages_insert on public.support_messages;
create policy support_messages_insert_admin on public.support_messages for insert to authenticated
  with check (author_id = (select auth.uid()) and author_role = 'admin' and (select public.is_admin()));

grant select on public.support_ticket_items, public.support_attachments to authenticated;
create policy support_ticket_items_select_admin on public.support_ticket_items for select to authenticated
  using ((select public.is_admin()));
create policy support_attachments_select_admin on public.support_attachments for select to authenticated
  using ((select public.is_admin()));

grant all on public.support_tickets, public.support_messages, public.support_ticket_items, public.support_attachments to service_role;

-- Photos du SAV : privées, affichées par des liens temporaires créés par le serveur.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('support-photos', 'support-photos', false, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;
